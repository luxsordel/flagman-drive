# The pilot runs in Belarus only: +375 and one of the mobile operator codes 25, 29, 33, 44.
# Clients normalize the input to E.164 before sending, so the server accepts exactly one form.
Phone = Annotated[
    str,
    Field(
        pattern=r"^\+375(25|29|33|44)[0-9]{7}$",
        description="Belarusian mobile number in E.164 format.",
        examples=["+375291234567"],
    ),
]

# [0-9] rather than \d: \d also matches non-ASCII digits.
OtpCode = Annotated[
    str,
    Field(pattern=r"^[0-9]{6}$", description="One-time code from the SMS.", examples=["123456"]),
]

# Mobile apps keep the refresh token in the OS keystore. A browser has no such place, so the web
# client gets it as an HttpOnly cookie that page scripts cannot read (docs/03-security.md).
RefreshTokenTransport = Literal["body", "cookie"]

# Issued tokens are shorter; the bounds only reject obvious garbage before any lookup.
RefreshToken = Annotated[
    str,
    Field(min_length=32, max_length=256, description="Opaque refresh token."),
]


