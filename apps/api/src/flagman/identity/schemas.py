from typing import Annotated, Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field

# The pilot runs in Belarus only: +375 and one of the mobile operator codes 25, 29, 33, 44.
# Clients normalize the input to E.164 before sending, so the server accepts exactly one form.
Phone = Annotated[
    str,
    Field(
        pattern=r"^\+375(25|29|33|44)[0-9]{7}$",
        description="Belarusian mobile number in E.164 format.",
        examples=["+375291234567"],
    ),
]

# [0-9] rather than \d: \d also matches non-ASCII digits.
OtpCode = Annotated[
    str,
    Field(pattern=r"^[0-9]{6}$", description="One-time code from the SMS.", examples=["123456"]),
]

# Issued tokens are shorter; the bounds only reject obvious garbage before any lookup.
RefreshToken = Annotated[
    str,
    Field(min_length=32, max_length=256, description="Opaque refresh token."),
]


class OtpRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    phone: Phone


class OtpRequestAccepted(BaseModel):
    """The same for every phone, so the response does not reveal whether a user exists."""

    model_config = ConfigDict(extra="forbid")

    expires_in: int = Field(description="Seconds the code stays valid.", examples=[300])
    resend_after: int = Field(
        description="Seconds before another code can be requested for this phone.",
        examples=[60],
    )


class OtpVerifyRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    phone: Phone
    code: OtpCode
    device_id: UUID = Field(
        description=(
            "Generated by the app once per installation and kept in secure storage. "
            "Reuse of an old refresh token revokes every session of this device."
        )
    )


class RefreshRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    refresh_token: RefreshToken


class LogoutRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    refresh_token: RefreshToken


class TokenPair(BaseModel):
    model_config = ConfigDict(extra="forbid")

    access_token: str = Field(description="JWT for the `Authorization: Bearer` header.")
    token_type: Literal["Bearer"] = "Bearer"  # noqa: S105 - the RFC 6750 scheme name, not a secret
    expires_in: int = Field(description="Seconds the access token stays valid.", examples=[900])
    refresh_token: str = Field(
        description="Single-use: every refresh returns a new one and invalidates this one."
    )
